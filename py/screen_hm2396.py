#!/usr/bin/env python3
"""Exact multiplier screens and a small bordered search for order 2396."""

from collections import defaultdict
from itertools import combinations, product
from math import gcd, isqrt

from reconstruct_hm668 import validate_h4_star
from search_sds_515 import multiplicative_orbits, row_sum_quadruples


ORDER = 2396
GS_LENGTH = ORDER // 4
BORDERED_LENGTH = GS_LENGTH - 1
BORDERED_EXPONENT = 132  # lcm(12, 22)


def cyclic_subgroup(generator):
    return frozenset(pow(generator, exponent, BORDERED_LENGTH) for exponent in range(BORDERED_EXPONENT))


def subgroup_product(left, right):
    return frozenset(a * b % BORDERED_LENGTH for a in left for b in right)


def gs_multiplier_cases():
    # 599 is prime. A subgroup of order d has one fixed point and all other
    # orbits of size d. Starting with all + signs on nonzero points gives
    # row sum 598 ± 1, and flipping a nonzero orbit changes it by 2d.
    cases = row_sum_quadruples(ORDER)
    return {
        size: [row for row in cases
               if all((r - GS_LENGTH + 1) % (2 * size) in (1, 2 * size - 1) for r in row)]
        for size in range(2, GS_LENGTH)
        if (GS_LENGTH - 1) % size == 0
    }


def bordered_subgroups():
    # U(598) is C12 × C22, so every subgroup has at most two generators.
    n = BORDERED_LENGTH
    cyclic = {cyclic_subgroup(a) for a in range(1, n) if gcd(a, n) == 1}
    groups = cyclic | {subgroup_product(left, right) for left, right in combinations(cyclic, 2)}
    return sorted((tuple(sorted(group)) for group in groups), key=lambda group: (len(group), group))


def signed_sums(sizes):
    sums = {0}
    for size in sizes:
        sums = {total + sign * size for total in sums for sign in (-1, 1)}
    return sums


def alternating_energy_cases(half_orbit_sizes):
    # Multipliers preserve parity, and translating by 299 pairs the two
    # halves' orbits. Their sign choices are independent.
    half_sums = signed_sums(half_orbit_sizes)
    square_sets = []
    for row_sum in (2, 0):
        square_sets.append({
            (2 * even_sum - row_sum) ** 2
            for even_sum in half_sums
            if row_sum - even_sum in half_sums and abs(2 * even_sum - row_sum) <= isqrt(ORDER)
        })
    first_squares, other_squares = square_sets
    cases = set()
    for a, b, c in product(first_squares, other_squares, other_squares):
        d = ORDER - a - b - c
        if b <= c <= d and d in other_squares:
            cases.add((isqrt(a), isqrt(b), isqrt(c), isqrt(d)))
    return sorted(cases)


def rotate(bits, shift, length):
    return ((bits << shift) | (bits >> (length - shift))) & ((1 << length) - 1)


def packed_profile(bits, shifts):
    # Half the Hamming distance at each shift counts + to - disagreements.
    # Ten bits per coordinate suffice even when summing two row profiles.
    return sum(
        (bin(bits ^ rotate(bits, shift, BORDERED_LENGTH)).count("1") // 2) << (10 * index)
        for index, shift in enumerate(shifts)
    )


def exact_small_bordered_shard():
    """Meet in the middle for the 24-orbit subgroup generated by 25 and 31."""
    n = BORDERED_LENGTH
    group = subgroup_product(cyclic_subgroup(25), cyclic_subgroup(31))
    even_orbits = multiplicative_orbits(range(0, n, 2), group, n)
    signed_group = group | {(-unit) % n for unit in group}
    shifts = [orbit[0] for orbit in multiplicative_orbits(range(1, n), signed_group, n)]
    masks = [sum(1 << residue for residue in orbit) for orbit in even_orbits]
    halves = defaultdict(list)
    for choices in product((0, 1), repeat=len(masks)):
        bits = sum(mask for mask, selected in zip(masks, choices) if selected)
        halves[2 * bin(bits).count("1") - n // 2].append(bits)

    for alternating_sums in alternating_energy_cases([len(orbit) for orbit in even_orbits]):
        pools = []
        for row_sum, alternating_sum in zip((2, 0, 0, 0), alternating_sums):
            even_sum = (row_sum + alternating_sum) // 2
            odd_sum = (row_sum - alternating_sum) // 2
            profiles = {}
            for even_bits, odd_bits in product(halves[even_sum], halves[odd_sum]):
                bits = even_bits | rotate(odd_bits, n // 2, n)
                profiles[packed_profile(bits, shifts)] = bits
            pools.append(profiles)
        a, b, c, d = pools
        left_pairs = product(a.items(), c.items())
        left = {
            profile_a + profile_c: (bits_a, bits_c)
            for (profile_a, bits_a), (profile_c, bits_c) in left_pairs
        }
        # A row autocorrelation is n minus four times its profile count.
        # Each coordinate of a two-row sum is at most n, so subtracting
        # from the target n+1 never borrows across packed coordinates.
        target = sum((n + 1) << (10 * index) for index in range(len(shifts)))
        print(f"Exact <25,31>: alternating_sums={alternating_sums} "
              f"distinct_row_profiles={tuple(map(len, pools))} distinct_left_sums={len(left)} "
              f"right_pairs={len(b) * len(d)}")
        for (profile_b, bits_b), (profile_d, bits_d) in product(b.items(), d.items()):
            complement = target - profile_b - profile_d
            if complement in left:
                bits_a, bits_c = left[complement]
                return bits_a, bits_b, bits_c, bits_d
    return None


def mod11_fixed_slice_cases(generator):
    """Filter a cyclic subgroup containing the order-11 subgroup of U(598)."""
    n = BORDERED_LENGTH
    group = cyclic_subgroup(generator)
    length = n // 23
    even_orbits = multiplicative_orbits(range(0, n, 2), group, n)
    fixed_orbits = [orbit for orbit in even_orbits if orbit[0] % 23 == 0]
    other_sums = signed_sums(len(orbit) for orbit in even_orbits if orbit[0] % 23 != 0)
    fixed_masks = [sum(1 << (x // 23) for x in orbit) for orbit in fixed_orbits]
    fixed_halves = defaultdict(set)
    for signs in product((-1, 1), repeat=len(fixed_orbits)):
        bits = sum(mask for mask, sign in zip(fixed_masks, signs) if sign == 1)
        fixed_sum = 2 * bin(bits).count("1") - length // 2
        for other_sum in other_sums:
            fixed_halves[fixed_sum + other_sum].add(bits)

    projected_units = {sign * unit % length for unit in group for sign in (-1, 1)}
    shifts = [orbit[0] for orbit in multiplicative_orbits(range(1, length), projected_units, length)]
    cases = alternating_energy_cases([len(orbit) for orbit in even_orbits])
    survivors = []
    for alternating_sums in cases:
        pools = []
        for row_sum, alternating_sum in zip((2, 0, 0, 0), alternating_sums):
            even_sum = (row_sum + alternating_sum) // 2
            odd_sum = (row_sum - alternating_sum) // 2
            profiles = set()
            for even_bits, odd_bits in product(fixed_halves[even_sum], fixed_halves[odd_sum]):
                bits = even_bits | rotate(odd_bits, length // 2, length)
                profiles.add(tuple(
                    (length - 2 * bin(bits ^ rotate(bits, shift, length)).count("1")) % 11
                    for shift in shifts
                ))
            pools.append(profiles)
        a, b, c, d = pools
        left = {tuple((x + y) % 11 for x, y in zip(pa, pb)) for pa, pb in product(a, b)}
        if any(tuple((-4 - x - y) % 11 for x, y in zip(pc, pd)) in left
               for pc, pd in product(c, d)):
            survivors.append(alternating_sums)
    return len(cases), survivors


def main():
    print(f"GS positive sorted row sum cases: {len(row_sum_quadruples(ORDER))}")
    for size, cases in gs_multiplier_cases().items():
        print(f"GS multiplier order={size} row_sum_cases={len(cases)}")
    print("Bordered subgroups, smallest orbit counts first")
    results = []
    for group in bordered_subgroups():
        orbits = multiplicative_orbits(range(0, BORDERED_LENGTH, 2), group, BORDERED_LENGTH)
        cases = alternating_energy_cases([len(orbit) for orbit in orbits])
        results.append((2 * len(orbits), group, cases))
    for orbit_count, group, cases in sorted(results):
        print(f"size={len(group):3} orbits={orbit_count:3} elements={group[:6]} "
              f"alternating_energy_cases={len(cases)}")
    print(f"Bordered parity screen: {sum(bool(cases) for _, _, cases in results)}/{len(results)} survive")
    for generator in (3, 25):
        case_count, survivors = mod11_fixed_slice_cases(generator)
        print(f"Mod-11 fixed-slice screen <{generator}>: {len(survivors)}/{case_count} cases survive")
    witness = exact_small_bordered_shard()
    if witness is None:
        print("Exact <25,31>: no complementary quadruple")
    else:
        rows = [tuple(1 if (bits >> index) & 1 else -1 for index in range(BORDERED_LENGTH))
                for bits in witness]
        validate_h4_star(rows)
        for row in rows:
            print("".join("+" if sign == 1 else "-" for sign in row))


if __name__ == "__main__":
    main()
